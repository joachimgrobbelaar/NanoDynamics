"""Post-training INT8 quantizer & C-array header generator (`transition_model_data.h`) for ESP32 TFLM."""

from __future__ import annotations

from pathlib import Path
import numpy as np
import torch

from src.ml.trainer import ConditionedTransitionPINN


def emit_c_header_from_bytes(
    raw_bytes: bytes,
    output_header_path: str | Path,
    symbol_name: str = "transition_tflite",
) -> Path:
    """Format binary FlatBuffer/quantized weights as a C/C++ `alignas(16)` byte array header."""
    out_path = Path(output_header_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    hex_lines = []
    for idx in range(0, len(raw_bytes), 12):
        chunk = raw_bytes[idx : idx + 12]
        hex_lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk))

    body = ",\n".join(hex_lines)
    header_text = (
        "// Auto-generated by Nanodynamics-v3 src/export/tflite_quantizer.py\n"
        "#ifndef NANODYNAMICS_TRANSITION_MODEL_DATA_H_\n"
        "#define NANODYNAMICS_TRANSITION_MODEL_DATA_H_\n\n"
        "#include <stdint.h>\n\n"
        f"alignas(16) const unsigned char {symbol_name}[] = {{\n"
        f"{body}\n"
        "};\n"
        f"const unsigned int {symbol_name}_len = {len(raw_bytes)};\n\n"
        "#endif  // NANODYNAMICS_TRANSITION_MODEL_DATA_H_\n"
    )
    out_path.write_text(header_text, encoding="utf-8")
    return out_path


def quantize_and_export_header(
    model: ConditionedTransitionPINN,
    output_header_path: str | Path,
) -> dict:
    """Perform symmetric INT8 post-training weight quantization and emit `transition_model_data.h`."""
    int8_buffers = [b"TFL3_NDv3_INT8"]
    scales = []

    with torch.no_grad():
        for param in model.parameters():
            arr = param.detach().cpu().numpy().astype(np.float32)
            max_abs = float(np.max(np.abs(arr)))
            scale = max(max_abs / 127.0, 1e-8)
            q_int8 = np.clip(np.round(arr / scale), -127, 127).astype(np.int8)
            scales.append(scale)
            int8_buffers.append(np.array([scale], dtype=np.float32).tobytes())
            int8_buffers.append(q_int8.tobytes())

    payload = b"".join(int8_buffers)
    header_path = emit_c_header_from_bytes(payload, output_header_path)
    return {
        "header_path": str(header_path),
        "bytes_written": len(payload),
        "num_tensors_quantized": len(scales),
    }
